type TFn = (key: string, fallback?: string) => string;

/** Wrap the app's t so kit keys resolve to a bundled DE/EN string when
 *  the backend catalog is absent (offline PWA). */
export function wrapKitT(t: TFn, lang: string): TFn {
    const map = lang === "de" ? KIT_DE : KIT_EN;
    return (key, fallback) => t(key, map[key] ?? fallback);
}
